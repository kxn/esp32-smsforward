"""Generate the compact read-only GBK-to-Unicode table used by Feishu MMS."""
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "main" / "feishu_gbk_table.h"


def main() -> None:
    values: list[int] = []
    for lead in range(0x81, 0xFF):
        for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFF)):
            try:
                decoded = bytes((lead, trail)).decode("gbk")
            except UnicodeDecodeError:
                values.append(0)
                continue
            codepoint = ord(decoded) if len(decoded) == 1 else 0
            values.append(codepoint if codepoint <= 0xFFFF else 0)

    lines = [
        "/* Generated by tools/gen_feishu_gbk_table.py; zero entries are invalid. */",
        "static const uint16_t s_gbk_to_unicode[126u * 190u] = {",
    ]
    for start in range(0, len(values), 12):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in values[start:start + 12]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
