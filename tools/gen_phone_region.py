"""Generate the firmware's flash-resident mainland mobile prefix table."""

import argparse
from hashlib import sha256
from pathlib import Path
import struct
from urllib.request import urlopen


REVISION = "62ad757490c8cd71d7456101bf7ea2629ca62f13"
SOURCE_URL = f"https://raw.githubusercontent.com/jieeit/phone/{REVISION}/src/data/phone.dat"
SOURCE_HASH = "115937ca789f98b854c0a61b63bfdf8950923f764575a236ac75e5d03081bcaf"
FIRST_PREFIX = 1_300_000
PREFIX_COUNT = 700_000
GROUP_WIDTH = 100
LABEL_BITS = 9
FLASH_LIMIT = 450 * 1024
OUTPUT = Path(__file__).resolve().parents[1] / "firmware/main/phone_region_data.inc"


def read_text(data, offset):
    size, = struct.unpack_from("<H", data, offset)
    start = offset + 2
    stop = start + size
    return data[start:stop].decode("utf-8"), stop


def parse_database(data):
    magic, version, _, count, index, index_size, dictionary, dict_size, cities, _ = (
        struct.unpack_from("<4sHH7I", data)
    )
    record = struct.Struct("<IIHH")
    if (magic, version, index, index_size, dictionary, dictionary + dict_size) != (
        b"JPHN", 3, 36, count * record.size, 36 + index_size, len(data)
    ):
        raise ValueError("Unexpected phone.dat header")

    labels = []
    offset = dictionary
    for _ in range(cities):
        province, offset = read_text(data, offset)
        city, offset = read_text(data, offset)
        label = province if province == city else province + city
        if not label or "\0" in label:
            raise ValueError("Invalid upstream location label")
        labels.append(label)
    if offset != len(data):
        raise ValueError("Unexpected data after the location dictionary")

    prefixes = {}
    for prefix, city_id, _, _ in record.iter_unpack(data[index:dictionary]):
        if not FIRST_PREFIX <= prefix < FIRST_PREFIX + PREFIX_COUNT or prefix in prefixes:
            raise ValueError(f"Unexpected prefix {prefix}")
        prefixes[prefix] = labels[city_id]
    return prefixes


def c_array(type_name, name, values):
    lines = [f"static const {type_name} {name}[] = {{"]
    for start in range(0, len(values), 12):
        lines.append("    " + ", ".join(map(str, values[start : start + 12])) + ",")
    return "\n".join(lines + ["};", ""])


def build_table(prefixes):
    labels = sorted(set(prefixes.values()))
    if len(labels) >= 1 << LABEL_BITS:
        raise ValueError("Location IDs exceed the packed index width")
    # Zero means unknown. Record the boundary when a populated run returns to zero
    # so a lookup inside an unassigned range never inherits its neighbor's label.
    ids = {label: idx for idx, label in enumerate(labels, 1)}
    groups = []
    boundaries = []
    for group_start in range(FIRST_PREFIX, FIRST_PREFIX + PREFIX_COUNT, GROUP_WIDTH):
        groups.append(len(boundaries))
        previous = 0
        for suffix in range(GROUP_WIDTH):
            label_id = ids.get(prefixes.get(group_start + suffix), 0)
            if label_id != previous:
                boundaries.append((suffix << LABEL_BITS) | label_id)
                previous = label_id
    groups.append(len(boundaries))

    label_offsets = [0]
    locations = []
    label_size = 0
    for label in labels:
        encoded = label.encode("utf-8")
        label_offsets.append(label_size)
        locations.append('    "' + "".join(f"\\x{byte:02x}" for byte in encoded) + '\\0"')
        label_size += len(encoded) + 1

    size = 4 * len(groups) + 2 * (len(boundaries) + len(label_offsets)) + label_size + 1
    if label_size >= 1 << 16 or size > FLASH_LIMIT:
        raise ValueError(f"Lookup table too large: {size} bytes")
    table = [
        "/* Generated by tools/gen_phone_region.py. See docs/PHONE_REGION_DATA.md.",
        " * Location data: Copyright (c) 2026 Jieeit. SPDX-License-Identifier: MIT",
        " */",
        f"enum {{ REGION_FIRST_PREFIX = {FIRST_PREFIX}, REGION_PREFIX_COUNT = {PREFIX_COUNT},",
        f"       REGION_GROUP_WIDTH = {GROUP_WIDTH}, REGION_LABEL_BITS = {LABEL_BITS} }};",
        c_array("uint32_t", "region_groups", groups),
        c_array("uint16_t", "region_boundaries", boundaries),
        c_array("uint16_t", "region_label_offsets", label_offsets),
        "static const char region_labels[] =",
        *locations,
        ";",
        "",
    ]
    print(f"{len(prefixes):,} prefixes, {len(labels)} labels, {size:,} table bytes")
    return "\n".join(table).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="use a local copy of the pinned phone.dat")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="generated C include path")
    parser.add_argument("--check", action="store_true", help="verify output matches without writing")
    args = parser.parse_args()
    if args.source:
        data = args.source.read_bytes()
    else:
        with urlopen(SOURCE_URL, timeout=30) as response:
            data = response.read()
    if sha256(data).hexdigest() != SOURCE_HASH:
        parser.error("phone.dat SHA-256 does not match the pinned source")
    generated = build_table(parse_database(data))
    if args.check:
        if generated != args.output.read_bytes():
            parser.error("generated phone region table differs")
    else:
        args.output.write_bytes(generated)


if __name__ == "__main__":
    main()
